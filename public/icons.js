function iconSVG(name, size = 16) {
  const m = ICONS[name];
  if (!m) return '';
  let r = '';
  m.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (!PAL[ch]) { x++; continue; }
      let w = 1;
      while (row[x + w] === ch) w++;
      r += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${PAL[ch]}"/>`;
      x += w;
    }
  });
  return `<svg class="px" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}
function paintIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    if (el.dataset.painted === el.dataset.icon) return;
    el.innerHTML = iconSVG(el.dataset.icon, +(el.dataset.size || 16));
    el.dataset.painted = el.dataset.icon;
  });
}
